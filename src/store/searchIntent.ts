/**
 * 「这一轮要不要联网」的判断规则。
 *
 * 单独拎出来是为了能验：主流程那边要真发一次小请求问模型，而这件事
 * 一旦模型没配好（密钥错、本地服务没开）就什么都验不出来。规则本身
 * 是纯函数，跟网络无关，该单独测。
 *
 * 为什么要先过一道本地筛：多数提问是在处理手头这段文字（润色、翻译、
 * 总结），这些一律不该联网。全交给模型判断的话，每写一句话都要多等
 * 一次往返；而模型还偶尔会答「要不我查一下」——为一句话白等两秒不值。
 */

/** 明显是在处理手头文字的动作 */
export const EDIT_ONLY =
  /(改写|润色|扩写|缩写|续写|翻译|总结|概括|提炼|整理|重写|校对|错别字|排版|换行|缩进|分段|拆成|分成|列成|写成|这段|这篇|这句话|上面|刚才|帮我改|帮我写|加个|去掉|删掉)/

/**
 * 事实性信号。
 *
 * 「总结一下今年的政策」里也有「总结」，但它要的是事实，不是文字加工 ——
 * 所以上面那条规则还得看有没有这些词，命中就照样交去判断。
 */
export const FACT_CUE =
  /(最新|最近|今年|今天|昨天|明天|现在|目前|当前|多少钱|价格|费用|股价|汇率|版本|新闻|发布|上线|政策|法规|规定|标准|什么时候|哪一年|是谁|哪位|天气|赛程|比分|支持不|支持吗|报错|怎么解决)/

/** 这道筛子说「不用问模型了，直接答」 */
export function skipModelJudge(text: string): boolean {
  const s = text.trim()
  if (!s) return true

  /* 编辑指令的形状是「动作 + 冒号 + 材料」：
   *   把这句话改得通顺一点：我今天去学校的时候看到了一只猫
   * 冒号后面是给模型看的正文，里面的「今天」「天气」只是句子内容，
   * 不是用户在问事实。所以先按冒号切一刀，只看指令本身。
   * （不切的话，「翻译成英文：今天天气不错」会被正文里的「天气」判成
   *   要联网 —— 这条当初就是这么被验出来的。） */
  const cut = s.search(/[：:]/)
  if (cut > 0) {
    const head = s.slice(0, cut)
    if (EDIT_ONLY.test(head)) return !FACT_CUE.test(head)
  }

  if (!EDIT_ONLY.test(s)) return false
  return !FACT_CUE.test(s)
}

/**
 * 解析模型的判断结果。
 *
 * 只认 `SEARCH: 关键词`。模型可能回 `SEARCH：关键词`（全角冒号）、
 * 可能给关键词加引号、可能啰嗦两句再说 —— 前半段宽松，但**解析不出
 * 就当作不查**：宁可少查一次，也不能拿一段乱码去搜索框里搜。
 */
export function parseJudge(raw: string): string | null {
  const m = /SEARCH\s*[:：]\s*([^\n]+)/i.exec(raw ?? '')
  if (!m) return null
  const term = m[1]
    .trim()
    .replace(/^[「"'（(“]+/, '')
    .replace(/[」"'）)”]+$/, '')
    // 有的模型会在后面补一句「（这是检索词）」，把括号之后的东西削掉
    .replace(/\s*[（(].*$/, '')
    .trim()
    .slice(0, 80)
  return term || null
}

/**
 * 回答里「我答不上来」的信号。
 *
 * 前置判断猜错的时候（问的是事实，却被判成「不用查」），模型会老老实实
 * 说自己查不到、知识只到某个时间点、建议用户自己去搜。这句话不该原样
 * 交给用户 —— 它等于把「我没查到」包装成答案。看到这些词就补查一次。
 *
 * 只认明确的推脱措辞，不认「不确定」这种：正常回答里也常出现
 * 「具体时间我不确定，但……」——那是在诚实地标注某个细节，不是说整段
 * 答不出来。误判的代价是白搜一次、白答一遍，比漏判更贵。
 */
export const UNSURE_CUE =
  /(我无法(?:确定|确认|回答|获取|提供)|我(?:并)?不能(?:确定|确认回答)|无法确认|知识(?:只到|截止|更新到|库只到)|训练数据(?:只到|截至)|没有(?:找到|查到)(?:相关|这方面|最新)|资料不足|信息不足|需要(?:联网|实时|最新)(?:资料|信息|查询)|建议(?:你|您)?(?:自己)?(?:去)?(?:查询|搜索|查阅)最新)/

/** 这段回答是不是在说「我答不出来」 */
export function looksUnsure(answer: string): boolean {
  const s = (answer ?? '').trim()
  if (!s) return false
  /* 只看开头一段：答到一半顺口补一句「具体价格不确定」是正常的行文，
     而真正答不出来的时候，这句话一定在结论位置上（开头或结尾） */
  return UNSURE_CUE.test(s.slice(0, 300)) || UNSURE_CUE.test(s.slice(-200))
}
